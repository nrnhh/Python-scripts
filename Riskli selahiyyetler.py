def save_formatted_excel(df, file_name):
    writer = pd.ExcelWriter(file_name, engine='xlsxwriter')
    df.to_excel(writer, index=False, sheet_name='Hesabat')
    workbook  = writer.book
    worksheet = writer.sheets['Hesabat']

    header_format = workbook.add_format({
        'bold': True,
        'align': 'center',      
        'valign': 'vcenter',    
        'fg_color': '#4F81BD',
        'font_color': 'white',
        'border': 1
    })

    cell_format = workbook.add_format({
        'align': 'center',
        'valign': 'vcenter',
        'border': 1
    })

    for col_num, value in enumerate(df.columns.values):
        worksheet.write(0, col_num, value, header_format)

    for i, col in enumerate(df.columns):
        max_data_len = df[col].apply(lambda x: len(str(x))).max()
        column_len = max(max_data_len, len(str(col))) + 2
        column_len = min(column_len, 50)
        worksheet.set_column(i, i, column_len, cell_format)

    worksheet.freeze_panes(1, 0)
    writer.close()

def send_email(to_emails, cc_emails, subject, file_path):
    msg = EmailMessage()
    msg['Subject'] = subject
    msg['From'] = SENDER_EMAIL
    msg['To'] = ", ".join(to_emails)
    msg['Cc'] = ", ".join(cc_emails)
    
    body_text = """Hörmətli Klinika Rəhbərliyi,

Klinika üzrə riskli hesab edilən səlahiyyətlərə (Sil, Dəyişdir, Yenilə, Ləğv et, Rədd et) malik istifadəçilərin siyahısını əlavə edirəm.
Zəhmət olmasa, siyahıya baxış keçirib rəy bildirəsiniz.

Hörmətlə,"""

    msg.set_content(body_text)

    with open(file_path, 'rb') as f:
        msg.add_attachment(f.read(), maintype='application', 
                           subtype='vnd.openxmlformats-officedocument.spreadsheetml.sheet', 
                           filename=os.path.basename(file_path))

    try:
        with smtplib.SMTP(SMTP_SERVER, SMTP_PORT) as server:
            server.starttls()
            server.login(SENDER_EMAIL, SENDER_PASS)
            server.send_message(msg)
    except Exception as e:
        print(f" -> XƏTA (SMTP Bağlantısı): E-poçt serverinə qoşularkən xəta baş verdi: {e}")

